//! Integration tests: `rtk deps` summarises the dependency manifests it finds.

use std::fs;
use std::path::Path;

mod common;

fn deps(path: &Path) -> String {
    let output = common::rtk_command()
        .arg("deps")
        .arg(path)
        .output()
        .expect("spawn rtk deps");
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
    String::from_utf8_lossy(&output.stdout).into_owned()
}

/// A manifest long enough that its summary is the shorter of the two.
fn cargo_toml() -> String {
    let mut toml =
        String::from("[package]\nname = \"croft\"\nversion = \"0.1.0\"\n\n[dependencies]\n");
    for i in 0..12 {
        if i % 2 == 0 {
            toml.push_str(&format!("dep{i} = \"1.{i}\"\n"));
        } else {
            toml.push_str(&format!(
                "dep{i} = {{ version = \"2.{i}\", features = [\"full\", \"derive\", \"serde\"] }}\n"
            ));
        }
    }
    toml.push_str("\n[dev-dependencies]\n");
    for i in 0..6 {
        toml.push_str(&format!("dev{i} = \"0.{i}\"\n"));
    }
    toml.push_str("\n[build-dependencies]\ncc = \"1\"\n");
    toml
}

#[test]
fn cargo_summary_lists_dependencies_and_counts_the_rest() {
    let dir = common::tempdir();
    fs::write(dir.path().join("Cargo.toml"), cargo_toml()).expect("write Cargo.toml");
    let out = deps(dir.path());
    let mut expected = String::from("Rust (Cargo.toml):\n  Dependencies (12):\n");
    for i in 0..10 {
        let version = if i % 2 == 0 {
            format!("1.{i}")
        } else {
            format!("2.{i}")
        };
        expected.push_str(&format!("    dep{i} ({version})\n"));
    }
    expected.push_str("    ... +2 more\n  Dev (6):\n");
    for i in 0..5 {
        expected.push_str(&format!("    dev{i} (0.{i})\n"));
    }
    expected.push_str("    ... +1 more\n");
    assert_eq!(out, expected, "build-dependencies are not listed");
}

#[test]
fn each_manifest_in_the_folder_gets_its_own_section() {
    let dir = common::tempdir();
    let d = dir.path();
    fs::write(
        d.join("package.json"),
        r#"{"name": "croft-web", "version": "2.0.0",
            "dependencies": {"react": "^19.0.0", "zod": "^4.1.0"},
            "devDependencies": {"vitest": "^3.0.0", "typescript": "^5.9.0"},
            "description": "a manifest padded so the summary is shorter than the files it reads"}"#,
    )
    .expect("write package.json");
    fs::write(
        d.join("requirements.txt"),
        "# runtime\nrequests>=2.32\n\nflask==3.1.0\nnumpy\n",
    )
    .expect("write requirements.txt");
    fs::write(
        d.join("go.mod"),
        "// Code generated by the croft release tooling; edit go.work instead of this file.
module example.com/croft\n\ngo 1.24\n\nrequire (\n\tgithub.com/spf13/cobra v1.9.1\n\t// indirect below\n\tgolang.org/x/sys v0.33.0 // indirect\n)\n\nrequire github.com/pkg/errors v0.9.1\n",
    )
    .expect("write go.mod");
    let out = deps(d);
    assert_eq!(
        out,
        "Node.js (package.json):\n  croft-web @ 2.0.0\n  Dependencies (2):\n    react (^19.0.0)\n    zod (^4.1.0)\n  Dev Dependencies (2):\n    vitest\n    typescript\n\
         Python (requirements.txt):\n  Packages (3):\n    requests>=2.32\n    flask==3.1.0\n    numpy\n\
         Go (go.mod):\n  example.com/croft (go 1.24)\n  Dependencies (3):\n    github.com/spf13/cobra v1.9.1\n    golang.org/x/sys v0.33.0\n    github.com/pkg/errors v0.9.1\n"
    );
}

#[test]
fn a_manifest_path_reads_its_folder() {
    let dir = common::tempdir();
    let manifest = dir.path().join("Cargo.toml");
    fs::write(&manifest, cargo_toml()).expect("write Cargo.toml");
    assert_eq!(deps(&manifest), deps(dir.path()));
}

#[test]
fn a_folder_without_manifests_says_so() {
    let dir = common::tempdir();
    let out = deps(dir.path());
    assert_eq!(
        out,
        format!("No dependency files found in {}", dir.path().display())
    );
}

#[test]
fn a_manifest_shorter_than_its_summary_is_printed_as_is() {
    let dir = common::tempdir();
    let raw = "[dependencies]\na=\"1\"\n";
    fs::write(dir.path().join("Cargo.toml"), raw).expect("write Cargo.toml");
    assert_eq!(deps(dir.path()), raw);
}

/// Pads a manifest so its summary is the shorter of the two.
const PADDING: &str =
    "# A comment long enough that the summary is shorter than the manifest it reads.\n";

#[test]
fn cargo_summary_counts_path_git_workspace_and_target_dependencies() {
    let dir = common::tempdir();
    let toml = format!(
        "{PADDING}[package]\nname = \"croft\"\n\n[dependencies]\nserde = \"1\"\n\
         local = {{ path = \"../local\" }}\nfork = {{ git = \"https://example.com/fork.git\" }}\n\
         shared = {{ workspace = true }}\n\n\
         [target.'cfg(unix)'.dependencies]\nlibc = \"0.2\"\n\n\
         [target.'cfg(windows)'.dev-dependencies]\nwinapi-util = \"0.1\"\n\n\
         [dev-dependencies]\ntempfile = \"3\"\n\n\
         [workspace.dependencies]\nanyhow = \"1\"\n"
    );
    fs::write(dir.path().join("Cargo.toml"), toml).expect("write Cargo.toml");
    assert_eq!(
        deps(dir.path()),
        "Rust (Cargo.toml):\n  Dependencies (6):\n    serde (1)\n    local (path ../local)\n    \
         fork (git https://example.com/fork.git)\n    shared (workspace)\n    libc (0.2)\n    anyhow (1)\n\
         \x20 Dev (2):\n    winapi-util (0.1)\n    tempfile (3)\n"
    );
}

#[test]
fn pyproject_summary_separates_optional_dependencies_and_reads_one_line_lists() {
    let dir = common::tempdir();
    let toml = format!(
        "{PADDING}[project]\nname = \"croft\"\ndependencies = [\"requests>=2.32\", \"click\"]\n\n\
         [project.optional-dependencies]\ntest = [\n  \"pytest>=8\",\n]\n\n\
         [dependency-groups]\nlint = [\"ruff>=0.8\"]\n\n\
         [tool.ruff]\nline-length = 100\n"
    );
    fs::write(dir.path().join("pyproject.toml"), toml).expect("write pyproject.toml");
    assert_eq!(
        deps(dir.path()),
        "Python (pyproject.toml):\n  Dependencies (2):\n    requests>=2.32\n    click\n\
         \x20 Dev and optional (2):\n    pytest>=8\n    ruff>=0.8\n"
    );
}

#[test]
fn pyproject_summary_reads_poetry_tables() {
    let dir = common::tempdir();
    let toml = format!(
        "{PADDING}[tool.poetry]\nname = \"croft\"\n\n[tool.poetry.dependencies]\npython = \"^3.12\"\n\
         httpx = \"^0.28\"\nlocal = {{ path = \"../local\" }}\n\
         remote = {{ url = \"https://example.com/remote.whl\" }}\n\n\
         [tool.poetry.dev-dependencies]\nblack = \"^24\"\n\n\
         [tool.poetry.group.dev.dependencies]\nmypy = \"^1.13\"\n\n\
         [tool.black]\nline-length = 100\n"
    );
    fs::write(dir.path().join("pyproject.toml"), toml).expect("write pyproject.toml");
    assert_eq!(
        deps(dir.path()),
        "Python (pyproject.toml):\n  Dependencies (3):\n    httpx (^0.28)\n    local (path ../local)\n    \
         remote (url https://example.com/remote.whl)\n\
         \x20 Dev and optional (2):\n    black (^24)\n    mypy (^1.13)\n"
    );
}

#[test]
fn a_manifest_that_is_not_toml_fails_naming_the_file() {
    let dir = common::tempdir();
    fs::write(
        dir.path().join("Cargo.toml"),
        "[dependencies\nserde = \"1\"\n",
    )
    .expect("write Cargo.toml");
    let output = common::rtk_command()
        .arg("deps")
        .arg(dir.path())
        .output()
        .expect("spawn rtk deps");
    let stderr = String::from_utf8_lossy(&output.stderr);
    assert!(!output.status.success(), "{stderr}");
    assert!(
        stderr.contains("Failed to parse") && stderr.contains("Cargo.toml"),
        "{stderr}"
    );
}
