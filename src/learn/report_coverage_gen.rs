use super::{CorrectionRule, capitalize_first, format_console_report, write_rules_file};
use crate::core::test_isolation;
use crate::learn::detector::ErrorType;
use std::fs;

#[test]
fn console_report_omits_error_when_first_line_is_blank() {
    let rules = [CorrectionRule {
        wrong_pattern: "git commit --ammend".to_string(),
        right_pattern: "git commit --amend".to_string(),
        error_type: ErrorType::UnknownFlag,
        occurrences: 1,
        base_command: "git commit".to_string(),
        example_error: " \t\nerror: unexpected argument '--ammend'".to_string(),
    }];

    assert_eq!(
        format_console_report(&rules, 1, 1, 7),
        concat!(
            "RTK Learn -- 1 rules from 1 corrections (1 sessions, 7 days)\n",
            "\n",
            "     git commit --ammend  →  git commit --amend\n",
        ),
    );
}

#[test]
fn rules_file_replaces_empty_report_with_single_occurrence_rule() {
    let scratch = test_isolation::tempdir();
    let path = scratch.path().join("learn").join("cli-corrections.md");
    let path_str = path.to_str().unwrap();

    write_rules_file(&[], path_str).unwrap();
    assert_eq!(
        fs::read_to_string(&path).unwrap(),
        concat!(
            "# CLI Corrections (auto-generated by rtk learn)\n",
            "# Run `rtk learn --write-rules` to update\n\n",
            "No CLI corrections detected yet.\n",
        ),
    );

    let rules = [CorrectionRule {
        wrong_pattern: "git commit --ammend".to_string(),
        right_pattern: "git commit --amend".to_string(),
        error_type: ErrorType::UnknownFlag,
        occurrences: 1,
        base_command: "git commit".to_string(),
        example_error: "error: unexpected argument '--ammend'".to_string(),
    }];
    write_rules_file(&rules, path_str).unwrap();
    assert_eq!(
        fs::read_to_string(&path).unwrap(),
        concat!(
            "# CLI Corrections (auto-generated by rtk learn)\n",
            "# Run `rtk learn --write-rules` to update\n\n",
            "## Git commit\n",
            "- Use `git commit --amend` not `git commit --ammend`\n\n",
        ),
    );
}

#[test]
fn capitalize_first_handles_empty_and_expanding_initials() {
    assert!(capitalize_first("").is_empty());
    assert_eq!(capitalize_first("ßeta"), "SSeta");
}
